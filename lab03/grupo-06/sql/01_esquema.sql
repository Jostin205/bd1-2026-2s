CREATE SCHEMA hotel;
SET search_path TO hotel;

-- -----------------------------------------------------------------------------
-- persona  (lógico: Persona) — responsable de una reservación
-- Se omite MedioContactoPersona (fuera del subsistema; ver README, limitaciones).
-- -----------------------------------------------------------------------------
CREATE TABLE persona (
    id_persona       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tipo_documento   VARCHAR(30)  NOT NULL,
    numero_documento VARCHAR(30)  NOT NULL,
    nombre           VARCHAR(80)  NOT NULL,
    apellido1        VARCHAR(80)  NOT NULL,
    apellido2        VARCHAR(80),                       -- opcional (supuesto 1.7)
    fecha_nacimiento DATE         NOT NULL,
    nacionalidad     VARCHAR(60)  NOT NULL,
    CONSTRAINT pk_persona PRIMARY KEY (id_persona),
    -- RN-01: tipo + número de documento distinguen a cada persona
    CONSTRAINT uq_persona_documento UNIQUE (tipo_documento, numero_documento),
    CONSTRAINT ck_persona_textos CHECK (
        btrim(tipo_documento) <> '' AND btrim(numero_documento) <> ''
        AND btrim(nombre) <> '' AND btrim(apellido1) <> ''),
    CONSTRAINT ck_persona_nacimiento CHECK (fecha_nacimiento >= DATE '1900-01-01')
);

-- -----------------------------------------------------------------------------
-- empresa  (lógico: Empresa) — responsable alterno de una reservación
-- -----------------------------------------------------------------------------
CREATE TABLE empresa (
    id_empresa     INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(120) NOT NULL,
    medio_contacto VARCHAR(120) NOT NULL,               -- RN-03
    CONSTRAINT pk_empresa PRIMARY KEY (id_empresa),
    CONSTRAINT ck_empresa_textos CHECK (btrim(nombre) <> '' AND btrim(medio_contacto) <> '')
);

-- -----------------------------------------------------------------------------
-- categoria_habitacion  (lógico: CategoríaHabitación) — catálogo abierto
-- -----------------------------------------------------------------------------
CREATE TABLE categoria_habitacion (
    id_categoria       INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre             VARCHAR(60) NOT NULL,
    descripcion        TEXT,
    capacidad_habitual SMALLINT    NOT NULL,
    CONSTRAINT pk_categoria_habitacion PRIMARY KEY (id_categoria),
    CONSTRAINT uq_categoria_habitacion_nombre UNIQUE (nombre),
    CONSTRAINT ck_categoria_capacidad CHECK (capacidad_habitual > 0),
    CONSTRAINT ck_categoria_nombre CHECK (btrim(nombre) <> '')
);

-- -----------------------------------------------------------------------------
-- plan_tarifario  (lógico: PlanTarifario)
-- -----------------------------------------------------------------------------
CREATE TABLE plan_tarifario (
    id_plan         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre          VARCHAR(80) NOT NULL,
    condiciones     TEXT        NOT NULL,
    vigencia_inicio DATE        NOT NULL,
    vigencia_fin    DATE,                               -- NULL = sin fecha de fin
    CONSTRAINT pk_plan_tarifario PRIMARY KEY (id_plan),
    CONSTRAINT uq_plan_tarifario_nombre UNIQUE (nombre),
    CONSTRAINT ck_plan_vigencia CHECK (vigencia_fin IS NULL OR vigencia_fin >= vigencia_inicio),
    CONSTRAINT ck_plan_textos CHECK (btrim(nombre) <> '' AND btrim(condiciones) <> '')
);

-- -----------------------------------------------------------------------------
-- reservacion  (lógico: Reservación) — entidad principal del subsistema
-- -----------------------------------------------------------------------------
CREATE TABLE reservacion (
    id_reservacion         INTEGER GENERATED BY DEFAULT AS IDENTITY,
    id_persona_responsable INTEGER,
    id_empresa_responsable INTEGER,
    fecha_solicitud        DATE         NOT NULL DEFAULT CURRENT_DATE,
    fecha_entrada_prevista DATE         NOT NULL,
    fecha_salida_prevista  DATE         NOT NULL,
    cantidad_huespedes     SMALLINT     NOT NULL,
    estado                 VARCHAR(30)  NOT NULL DEFAULT 'solicitada',
    adelanto_requerido     NUMERIC(12,2),               -- monto que exige la política, si aplica
    decision_adelanto      VARCHAR(10),                 -- RN-15
    CONSTRAINT pk_reservacion PRIMARY KEY (id_reservacion),
    CONSTRAINT fk_reservacion_persona FOREIGN KEY (id_persona_responsable)
        REFERENCES persona (id_persona),
    CONSTRAINT fk_reservacion_empresa FOREIGN KEY (id_empresa_responsable)
        REFERENCES empresa (id_empresa),
    -- RN-02/RN-03: exactamente un responsable (persona o empresa)
    CONSTRAINT ck_reservacion_responsable CHECK (
        (id_persona_responsable IS NOT NULL)::int + (id_empresa_responsable IS NOT NULL)::int = 1),
    CONSTRAINT ck_reservacion_fechas CHECK (fecha_salida_prevista > fecha_entrada_prevista),
    CONSTRAINT ck_reservacion_solicitud CHECK (fecha_solicitud <= fecha_entrada_prevista),
    CONSTRAINT ck_reservacion_huespedes CHECK (cantidad_huespedes > 0),
    CONSTRAINT ck_reservacion_estado CHECK (estado IN
        ('solicitada','confirmada','cancelada','vencida','no presentada','convertida en estancia')),
    CONSTRAINT ck_reservacion_adelanto CHECK (adelanto_requerido IS NULL OR adelanto_requerido >= 0),
    CONSTRAINT ck_reservacion_decision CHECK (decision_adelanto IS NULL
        OR decision_adelanto IN ('devolver','penalizar')),
    -- RN-15: la decisión sobre el adelanto solo existe si se canceló o no se presentó
    CONSTRAINT ck_reservacion_decision_estado CHECK (decision_adelanto IS NULL
        OR estado IN ('cancelada','no presentada'))
);

-- -----------------------------------------------------------------------------
-- detalle_reservacion  (lógico: DetalleReservación) — N:M Reservación × Categoría
-- Congela precio y condiciones al confirmar (RN-13).
-- -----------------------------------------------------------------------------
CREATE TABLE detalle_reservacion (
    id_reservacion        INTEGER       NOT NULL,
    id_categoria          INTEGER       NOT NULL,
    cantidad_habitaciones SMALLINT      NOT NULL,
    precio_pactado        NUMERIC(12,2) NOT NULL,       -- por noche, por habitación
    id_plan               INTEGER       NOT NULL,
    condiciones_pactadas  TEXT          NOT NULL,       -- copia congelada de plan_tarifario.condiciones
    CONSTRAINT pk_detalle_reservacion PRIMARY KEY (id_reservacion, id_categoria),
    CONSTRAINT fk_detalle_reservacion FOREIGN KEY (id_reservacion)
        REFERENCES reservacion (id_reservacion) ON DELETE CASCADE,
    CONSTRAINT fk_detalle_categoria FOREIGN KEY (id_categoria)
        REFERENCES categoria_habitacion (id_categoria),
    CONSTRAINT fk_detalle_plan FOREIGN KEY (id_plan)
        REFERENCES plan_tarifario (id_plan),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad_habitaciones > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_pactado >= 0),
    CONSTRAINT ck_detalle_condiciones CHECK (btrim(condiciones_pactadas) <> '')
);

-- -----------------------------------------------------------------------------
-- modificacion_reservacion  (lógico: ModificaciónReservación) — entidad débil
-- RN-14: cuándo, quién y si cambió el precio.
-- -----------------------------------------------------------------------------
CREATE TABLE modificacion_reservacion (
    id_reservacion          INTEGER      NOT NULL,
    id_modificacion         INTEGER      NOT NULL,      -- discriminador dentro de la reservación
    fecha_hora_modificacion TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_modificacion       VARCHAR(20)  NOT NULL,
    solicitante             VARCHAR(120) NOT NULL,
    genero_cambio_precio    BOOLEAN      NOT NULL DEFAULT FALSE,
    diferencia_precio       NUMERIC(12,2),
    descripcion_cambio      TEXT,
    CONSTRAINT pk_modificacion_reservacion PRIMARY KEY (id_reservacion, id_modificacion),
    CONSTRAINT fk_modificacion_reservacion FOREIGN KEY (id_reservacion)
        REFERENCES reservacion (id_reservacion) ON DELETE CASCADE,
    CONSTRAINT ck_modificacion_id CHECK (id_modificacion > 0),
    CONSTRAINT ck_modificacion_tipo CHECK (tipo_modificacion IN
        ('fechas','ocupacion','categorias','cancelacion')),
    CONSTRAINT ck_modificacion_solicitante CHECK (btrim(solicitante) <> ''),
    -- la diferencia de precio solo tiene valor si la modificación cambió el precio
    CONSTRAINT ck_modificacion_precio CHECK (genero_cambio_precio OR diferencia_precio IS NULL)
);

-- -----------------------------------------------------------------------------
-- pago  (lógico: Pago) — en este subsistema solo se usan los de tipo 'adelanto'
-- -----------------------------------------------------------------------------
CREATE TABLE pago (
    id_pago        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    monto          NUMERIC(12,2) NOT NULL,
    fecha          DATE          NOT NULL,
    medio          VARCHAR(20)   NOT NULL,
    referencia     VARCHAR(60),
    tipo           VARCHAR(10)   NOT NULL,
    id_reservacion INTEGER,
    CONSTRAINT pk_pago PRIMARY KEY (id_pago),
    CONSTRAINT fk_pago_reservacion FOREIGN KEY (id_reservacion)
        REFERENCES reservacion (id_reservacion),
    CONSTRAINT ck_pago_monto CHECK (monto > 0),
    CONSTRAINT ck_pago_medio CHECK (medio IN ('efectivo','tarjeta','transferencia','otro')),
    CONSTRAINT ck_pago_tipo CHECK (tipo IN ('adelanto','pago')),
    -- RN-15/RN-26: un adelanto siempre pertenece a una reservación
    CONSTRAINT ck_pago_adelanto CHECK (tipo <> 'adelanto' OR id_reservacion IS NOT NULL),
    -- Caso: no se almacenan datos sensibles completos de tarjetas. Se rechaza una
    -- referencia que parezca un número de tarjeta (13 a 23 caracteres numéricos,
    -- con espacios o guiones).
    CONSTRAINT ck_pago_referencia_sin_tarjeta CHECK (
        referencia IS NULL OR referencia !~ '^[0-9][0-9 -]{11,21}[0-9]$')
);

-- -----------------------------------------------------------------------------
-- Índices adicionales (los de PK y UNIQUE ya los crea PostgreSQL)
-- -----------------------------------------------------------------------------
-- 1) Consultas operativas y rutina de vencimiento filtran por estado y por fecha
--    de entrada (reservaciones pendientes, próximas llegadas, vencidas).
CREATE INDEX idx_reservacion_estado_entrada
    ON reservacion (estado, fecha_entrada_prevista);

-- 2) PostgreSQL no indexa automáticamente la columna que referencia (FK). El adelanto
--    de una reservación se busca en fn_decision_adelanto y en la rutina de vencimiento
--    (NOT EXISTS). Índice parcial: solo los pagos ligados a una reservación.
CREATE INDEX idx_pago_reservacion
    ON pago (id_reservacion) WHERE id_reservacion IS NOT NULL;

-- 3) La PK de detalle_reservacion empieza por id_reservacion; las consultas por
--    categoría (ingresos por categoría, disponibilidad) necesitan entrar por id_categoria.
CREATE INDEX idx_detalle_reservacion_categoria
    ON detalle_reservacion (id_categoria);
